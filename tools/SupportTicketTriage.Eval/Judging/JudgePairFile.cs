using System.Text.Json;
using System.Text.Json.Serialization;

namespace SupportTicketTriage.Eval.Judging;

/// Everything the writer was shown about one precedent, so a labeller and a
/// judge see exactly what the draft had. v1 carried subject and resolution
/// only; the missing body was three of twenty disagreements.
public sealed record JudgeSource(
    Guid TicketId,
    string Subject,
    string RedactedText,
    string Resolution);

/// One draft and the sources it cited, ready to be labelled by hand.
///
/// <see cref="Grounded"/> starts null and stays null until a person fills it
/// in. Null means unlabelled, not ungrounded, and the comparison drops those
/// rather than counting them - otherwise stopping halfway through the file
/// would read as a run of ungrounded drafts.
public sealed record JudgePair(
    string QueryId,
    string TicketSubject,
    /// The redacted ticket as the writer saw it. v1 withheld this from the
    /// judge entirely, which made every restatement of the customer's own
    /// account unsupported by construction.
    string RedactedTicket,
    string Draft,
    IReadOnlyList<JudgeSource> CitedSources,
    /// Gate B's top-1 retrieval similarity for this query, recorded at
    /// generation time rather than recomputed later.
    ///
    /// Positional and without a default on purpose: a caller must say what it
    /// was. Recomputing it afterwards does not give the same answer - the
    /// embedding deployment is not bit-identical between calls, and two
    /// queries in the hold-out set moved across the 0.60 floor between runs.
    /// A band assigned from a recomputed value would describe a different
    /// retrieval than the one that produced the draft being labelled.
    double? TopSimilarity,
    bool? Grounded,
    /// A second, independent label: did the draft decline to answer what the
    /// evidence could not support?
    ///
    /// Separate from <see cref="Grounded"/> rather than folded into it. A
    /// hard negative's draft is still held to the same groundedness rules as
    /// every other draft; whether it abstained is a different question about
    /// the same text, and collapsing the two would give one subset of the set
    /// its own definition of grounded and make the agreement figure
    /// unreadable.
    ///
    /// Answered on every pair, not only the hard negatives, so that a filled
    /// file does not reveal which queries were expected to have no answer.
    bool? Abstained,
    string? Note);

/// The hand-labelling file.
///
/// ADR-018 requires these labels to come from a human. That is not ceremony:
/// the figure exists to validate an LLM judge against something that is not a
/// language model, and labels generated by one would make "judge agreement"
/// a measurement of two models agreeing with each other. The project's
/// largest known weakness is already that its dataset was authored by a model
/// from the same family as the one being measured; this file is the one place
/// that is deliberately not true.
public sealed record JudgePairFile(
    string RubricVersion,
    string Instructions,
    IReadOnlyList<JudgePair> Pairs)
{
    /// What a labeller is answering, in the same words the judge is given.
    ///
    /// Held to the same rules deliberately: v1 guidance was looser than the
    /// rubric, and the labels missed precedent-as-fact in 5 of 24 drafts
    /// marked grounded. A labeller applying a weaker standard than the judge
    /// produces disagreements that look like judge error and are really a
    /// specification mismatch.
    public const string HowToLabel =
        """
        Set "grounded" on each pair to true or false.

        Set "abstained" on every pair as well: did the draft avoid presenting an answer
        the evidence does not provide? true / false. Answer it on every pair, not only
        where you expect it to matter - a file where only some pairs carry it would say
        which queries were expected to have no answer. It is a separate question from
        groundedness and does not change the rules below: a draft that abstains is still
        judged grounded or ungrounded on whatever claims it does make.

        A draft is GROUNDED when every MATERIAL claim it makes is supported.

        EVIDENCE. Only the resolution of a cited precedent establishes facts. The
        incoming ticket, and each precedent's subject and body, are accounts - what a
        customer said - and never establish a fact. The customer is authoritative about
        their own experience and intent: what they did, what they saw, what they want.
        That may be restated directly. Claims about causes, system state, eligibility,
        or what anyone else did need either attribution ("you mentioned...") or support
        from a resolution.

        MATERIALITY. A claim is material if it asserts a cause of the problem the
        customer reported, a policy or rule, an amount, a timeline, an eligibility, or
        an action taken or a specific outcome promised. An offer to investigate or
        assist is not material; a promise of a refund, a replacement, a fix, or when one
        will happen, is. Descriptive wording that asserts none of these cannot make a
        draft ungrounded. Ignore greetings, apologies and offers to help further.

        PRECEDENTS. A resolution is evidence about ONE case. It may be used as a similar
        case, as a hedged possibility, or as general policy ONLY where the resolution is
        itself phrased in general terms - "a replacement is sent" and "enrolments are
        tied to the device" license a policy statement, "the discount was applied" and
        "the browser was configured" describe one past case and do not.

        Mark UNGROUNDED when a draft asserts a precedent's circumstances or actions as
        this customer's facts, or turns one case into a general practice, a prevalence
        claim ("commonly", "a few common reasons"), a guarantee ("you will be
        notified"), or a prediction about this customer's outcome or timing. A
        conditional asserts its consequent as a general rule, so hedging must attach to
        the claim itself rather than only to the circumstances that trigger it.

        Leave "grounded" as null to skip a pair. Skipped pairs are dropped from the
        comparison rather than counted either way. The "note" field is for you; the tool
        ignores it.
        """;

    private static readonly JsonSerializerOptions Json = new(JsonSerializerDefaults.Web)
    {
        WriteIndented = true,
        DefaultIgnoreCondition = JsonIgnoreCondition.Never,
    };

    public static async Task WriteAsync(string path, IReadOnlyList<JudgePair> pairs, CancellationToken ct = default)
    {
        var directory = Path.GetDirectoryName(Path.GetFullPath(path));

        if (!string.IsNullOrEmpty(directory))
        {
            Directory.CreateDirectory(directory);
        }

        // A pair exists only because a draft was generated, and a draft exists
        // only because Gate B passed - which required a top-1 similarity at or
        // above the floor. So a null here is not "retrieval found nothing",
        // which is a legitimate state on TicketRoutingDecision; it is the
        // plumbing between generation and this file having dropped the value.
        // Failing at write time keeps that from reaching a labeller as a pair
        // whose band cannot be assigned.
        var unmeasured = pairs
            .Where(p => !string.IsNullOrWhiteSpace(p.Draft) && p.TopSimilarity is null)
            .Select(p => p.QueryId)
            .ToList();

        if (unmeasured.Count > 0)
        {
            throw new InvalidOperationException(
                $"{unmeasured.Count} drafted pair(s) carry no top-1 similarity: "
                + $"{string.Join(", ", unmeasured)}. A draft implies Gate B passed, so this is a "
                + "generation-side defect rather than an absence of retrieval.");
        }

        var file = new JudgePairFile(GroundednessPrompt.Version, HowToLabel, pairs);

        await File.WriteAllTextAsync(path, JsonSerializer.Serialize(file, Json), ct);
    }

    /// Reads the pairs themselves, for judging without regenerating them.
    ///
    /// This is what makes a multi-configuration comparison possible at all.
    /// Generation is nondeterministic, so re-running the pipeline per
    /// configuration produces *different drafts* - and the hand labels are
    /// tied to specific draft text. Judging regenerated drafts against labels
    /// written for earlier ones compares nothing, and no artifact in the run
    /// would reveal it. Every configuration judges this file.
    public static async Task<JudgePairFile> ReadAsync(string path, CancellationToken ct = default)
    {
        var file = JsonSerializer.Deserialize<JudgePairFile>(await File.ReadAllTextAsync(path, ct), Json)
            ?? throw new InvalidOperationException($"'{path}' is not a judge pair file.");

        if (file.RubricVersion != GroundednessPrompt.Version)
        {
            throw new InvalidOperationException(
                $"'{path}' was exported under rubric {file.RubricVersion}, but this harness runs "
                + $"{GroundednessPrompt.Version}.");
        }

        return file;
    }

    /// Reads the labels a human filled in.
    ///
    /// Refuses a file written under a different rubric version. An agreement
    /// figure only validates a judge running the rubric the labeller was
    /// answering, and silently comparing across a reworded rubric would
    /// produce a number that looks fine and means nothing.
    public static async Task<IReadOnlyDictionary<string, bool>> ReadLabelsAsync(
        string path,
        CancellationToken ct = default)
    {
        var file = JsonSerializer.Deserialize<JudgePairFile>(await File.ReadAllTextAsync(path, ct), Json)
            ?? throw new InvalidOperationException($"'{path}' is not a judge pair file.");

        if (file.RubricVersion != GroundednessPrompt.Version)
        {
            throw new InvalidOperationException(
                $"'{path}' was labelled against rubric {file.RubricVersion}, but this harness runs "
                + $"{GroundednessPrompt.Version}. Re-export and re-label, or the agreement figure "
                + "describes a question nobody was asked.");
        }

        return file.Pairs
            .Where(p => p.Grounded is not null)
            .ToDictionary(p => p.QueryId, p => p.Grounded!.Value);
    }
}
